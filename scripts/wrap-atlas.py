#!/usr/bin/env python3
"""Wrap computescope's GPU atlas page as a standalone page of this site.

The atlas is built on ml-engine (~/projects/computescope, `.venv/bin/python
-m computescope.atlas.build_prototype OUT.html`) for the Claude artifact host,
which supplies the <html>/<head>/<body> skeleton and a small body reset, and
lets the page load Three.js from cdnjs. This script turns that output into a
full document: a real head with charset, viewport and the site favicon, the
same minimal reset the host applied, the one <script src> pointed at the
vendored Three.js, and the host-specific meta tag dropped. Nothing else in
the page is touched, so a rebuilt atlas can be re-wrapped with one command.

Usage:
    scripts/wrap-atlas.py RAW.html [-o static/gpu-atlas/index.html]
"""
import argparse
import sys
from pathlib import Path

CDN_SRC = "https://cdnjs.cloudflare.com/ajax/libs/three.js/0.160.0/three.min.js"
LOCAL_SRC = "/vendor/three-0.160.0/three.min.js"
HOST_META = '<meta name="claude:viewport-fit-sides" content="cover">\n'

HEAD = """<!doctype html>
<!-- Generated by scripts/wrap-atlas.py from computescope's gpu-atlas.html.
     Do not edit by hand; rebuild the atlas on ml-engine and re-wrap. -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<link rel="icon" href="/favicon.ico" sizes="any">
<link rel="icon" href="/favicon.svg" type="image/svg+xml">
<style>body{margin:0}img{max-width:100%}[hidden]{display:none!important}</style>
<script>
/* Carry the blog's remembered appearance (Blowfish stores "dark"/"light" as
   localStorage.appearance) into the atlas, which reads data-theme on <html>
   and otherwise follows the OS, as the blog does. */
try{var a=localStorage.getItem("appearance");if(a==="dark"||a==="light")document.documentElement.setAttribute("data-theme",a);}catch(e){}
</script>
"""


def wrap(raw: str) -> str:
    if raw.count(CDN_SRC) != 1:
        sys.exit(f"expected exactly one Three.js script src, found {raw.count(CDN_SRC)}")
    raw = raw.replace(CDN_SRC, LOCAL_SRC)
    if HOST_META in raw:
        raw = raw.replace(HOST_META, "", 1)
    else:
        print("note: artifact-host meta tag not found; nothing dropped", file=sys.stderr)
    cut = raw.index("</style>") + len("</style>")
    head, body = raw[:cut], raw[cut:].lstrip("\n")
    return f"{HEAD}{head}\n</head>\n<body>\n{body}\n</body>\n</html>\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("raw", type=Path, help="gpu-atlas.html as built by computescope")
    ap.add_argument("-o", "--out", type=Path, default=Path("static/gpu-atlas/index.html"))
    a = ap.parse_args()
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text(wrap(a.raw.read_text()))
    print(f"wrote {a.out} ({a.out.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
